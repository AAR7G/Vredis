static void fd_set_nonblock(int fd) {
    int flags = fcntl(fd, F_GETFL, 0);
    if(flags == -1) {
        die("fcntl() error");
    }

    flags |= O_NONBLOCK;            //Sets non-blocking bit flag to 1

    flags = fcntl(fd, F_SETFL, flags);              
    if(flags == -1) {
        die("fcntl() error");
    }
}

static struct Conn *handle_accept(int fd) {
    //accept
    struct sockaddr_in client_addr = {};
    socklen_t addrlen = (socklen_t)sizeof(client_addr);
    int connfd = accept(fd, (struct sockaddr *)&client_addr, &addrlen);
    if(connfd < 0) {
        msg_errno("accept() error");
        return NULL;
    }

    uint32_t ip = client_addr.sin_addr.s_addr;
    fprintf(stderr, "new client from %u.%u.%u.%u:%u\n",
        ip & 255, (ip >> 8) & 255, (ip >> 16) & 255, ip >> 24, ntohs(client_addr.sin_port)
    );

    //Set the new connection fd to non-blocking mode
    fd_set_nonblock(connfd);

    //Create a 'struct Conn' to return
    struct Conn *conn = new Conn();
    conn->fd = connfd;
    conn->want_read = true;             //Read first request of the client

    return conn;
}

static void msg_errno(const char *msg) {
    fprintf(stderr, "[%d] %s", errno, msg);
}

//Application callback when socket is readable
static void handle_read(struct Conn *conn) {
    //do a read
    uint8_t buf[64 * 1024];
    ssize_t rv = read(conn->fd, buf, (size_t)sizeof(buf));
    if(rv < 0 && errno == EAGAIN) {
        return;         //Not actually ready
    }
    //handle IO error
    if(rv < 0) {
        msg_errno("read() error");
        conn->want_close = true;
        return;
    }
    //handle EOF
    if(rv == 0) {
        if(conn->incoming.size() == 0) {
            msg("Client closed");
        } else {
            msg("Unexpected EOF");
        }
        conn->want_close = true;
        return;
    }

    //Adding data to the 'Conn::incoming' buffer of size 'rv'
    buf_append(conn->incoming, buf, (size_t)rv);

    //repeatedly try to parse and process request
    while(try_one_request(conn)) { }            //Calling this in a loop due to pipelining
    //Keep looping as long as it successfully processes a message 
    //'try_one_request' handles only 1 complete message at a time, thus it needs to be repeated in case
    //there are multiple complete messages

    //Update the readiness intention and potentially write immeadiately
    if(conn->outgoing.size() > 0) {             //Have a response to send
        conn->want_read = false;                //Dont want to read anymore, until response is sent
        conn->want_write = true;
        //The socket is likely ready to write in a request response protocol
        //try to write without waiting for next iteration
        return handle_write(conn);
    } else {
        conn->want_read = true;                 //If no response to be sent, wait for a new request
        conn->want_write = false;
    }
}

//Process 1 complete message/request (If there is enough data)
static bool try_one_request(struct Conn *conn) {
    //Get message length from the header
    if(conn->incoming.size() < 4) {
        return false;                   //Need to read again for complete message
    }

    uint32_t len = 0;
    memcpy(&len, conn->incoming.data(), 4);
    if(len > k_max_msg) {               //Exceeds max size of message allowed (Protocol error)
        msg("Message is too long");
        conn->want_close = true;
        return false;
    }

    //Message body
    if(4 + len > conn->incoming.size()) {
        conn->want_read = true;         //If length of message in 'incoming' is lower than it should be,
        return false;                   //then complete message has not been read. Go back to read.
    }

    const uint8_t *request = &conn->incoming[4];

    //Got full request, now do some application logic
    std::vector<std::string> cmd;
    if(parse_req(request, len, cmd) < 0) {
        msg("Bad request");
        conn->want_close = true;
        return false;
    }

    size_t header_pos = 0;
    response_begin(conn->outgoing, &header_pos);
    do_request(cmd, conn->outgoing);
    response_end(conn->outgoing, header_pos);

    //Application logic complete, now clear the incoming buffer
    buf_consume(conn->incoming, 4 + len);           //We dont clear the buffer cuz of pipelining
    return true;
}

//Application callback when the socket is writable
static void handle_write(struct Conn *conn) {
    assert(conn->outgoing.size() > 0);
    ssize_t rv = write(conn->fd, conn->outgoing.data(), conn->outgoing.size());
    if(rv < 0 && errno == EAGAIN) {
        return;             //Not ready to write yet
    }
    if(rv < 0) {
        msg_errno("write() error");
        conn->want_close = true;
        return;
    }

    //remove data from 'outgoing' buffer
    buf_consume(conn->outgoing, (size_t)rv);

    //Update the readiness intention
    if(conn->outgoing.size() == 0) {            //All the data already written to the socket
        conn->want_read = true;                 //No more to write, thus read again
        conn->want_write = false;
    } else {
        conn->want_read = false;                //Since data to write left
        conn->want_write = true;
    }
}

//buf appends to the back and consumes from the front, making it a FIFO.
//append to the back
static void buf_append(Buffer &buf, const uint8_t *data, size_t len) {
    buf.insert(buf.end(), data, data + len);        //Will insert all from 'data' to 'data + len' in buf

}

//remove from the front
static void buf_consume(Buffer &buf, size_t len) {
    buf.erase(buf.begin(), buf.begin() + len);
}

const size_t k_max_args = 200 * 1000;               //Max no. of arguments in 1 command

// | nstr | len1 | str1 | len2 | str2 | ... | lenn | strn |
// n depends on nstr
static int32_t parse_req(const uint8_t *data, size_t size, std::vector<std::string> &cmd) {
    const uint8_t *end = data + size;
    uint32_t nstr = 0;                  //No. of strings in the command
    if(!read_len(data, end, nstr)) {
        return -1;
    }

    if(nstr > k_max_args) {
        return -1;
    }

    while(cmd.size() < nstr) {
        uint32_t len = 0;
        if(!read_len(data, end, len)) {
            return -1;
        }

        cmd.push_back(std::string());
        if(!read_str(data, end, len, cmd.back())) {
            return -1;
        }
    }

    if(data != end) {
        return -1;      //trailing garbage data present
    }

    return 0;
}

//Reads the 4Bytes that give the length/number of the string
static bool read_len(const uint8_t *&cur, const uint8_t *end, uint32_t &out) {
    if(cur + 4 > end) {
        return false;
    }

    memcpy(&out, cur, 4);
    cur += 4;
    return true;
}

//Read the actual strings in the command (One at a time) 
static bool read_str(const uint8_t *&cur, const uint8_t *end, size_t len, std::string &out) {
    if(cur + len > end) {
        return false;
    }

    out.assign(cur, cur + len);
    cur += len;
    return true;
}

//Error codes for TAG_ERR tag
enum {
    ERR_UNKNOWN = 1,        //Error (Unrecognised command)
    ERR_TOO_BIG = 2         //Response size too big
};

//Data types of all serialised data
enum {
    TAG_NIL,        //Null
    TAG_ERR,        //Error code + message
    TAG_STR,        //String
    TAG_INT,        //64 bit integer
    TAG_DBL,        //Double
    TAG_ARR         //Array
};

//Help functions for serialisation
static void buf_append_u8(Buffer &buf, uint8_t tag) {
    buf.push_back(tag);
}

static void buf_append_u32(Buffer &buf, uint32_t val) {
    buf_append(buf, (const uint8_t *)&val, 4);
}

static void buf_append_i64(Buffer &buf, int64_t val) {
    buf_append(buf, (const uint8_t *)&val, 8);
}

static void buf_append_dbl(Buffer &buf, double val) {
    buf_append(buf, (const uint8_t *)&val, 8);
}

//TLV (Tag Length Value) Format being used for serialisation
//Tag size is 1B;   Length size is 4B (Length part not used for fixed length data types);
//Value size is either fixed (Like 8B for int), or arbitrary for variable length complex types (Like strings or arrays)

//Append all the serialised data in TLV format to the back of the Buffer
static void out_nil(Buffer &out) {
    buf_append_u8(out, TAG_NIL);
}

static void out_int(Buffer &out, int64_t number) {
    buf_append_u8(out, TAG_INT);
    buf_append_i64(out, number);
}

static void out_str(Buffer &out, const char *s, size_t size) {
    buf_append_u8(out, TAG_STR);
    buf_append_u32(out, (uint32_t)size);
    buf_append(out, (const uint8_t *)s, size);
}

static void out_arr(Buffer &out, uint32_t n) {
    buf_append_u8(out, TAG_ARR);
    buf_append_u32(out, n);
}

static void out_dbl(Buffer &out, double val) {
    buf_append_u8(out, TAG_DBL);
    buf_append_dbl(out, val);
}

static void out_err(Buffer &out, uint32_t code, const std::string &msg) {
    buf_append_u8(out, TAG_ERR);
    buf_append_u32(out, code);
    buf_append_u32(out, (uint32_t)msg.size());
    buf_append(out, (const uint8_t *)msg.data(), msg.size());
}

static void do_request(std::vector<std::string> &cmd, Buffer &out) {
    if(cmd.size() == 2 && cmd[0] == "get") {
        return do_get(cmd, out);
    }
    else if(cmd.size() == 3 && cmd[0] == "set") {
        return do_set(cmd, out);
    }
    else if(cmd.size() == 2 && cmd[0] == "del") {
        return do_del(cmd, out);
    }
    else if(cmd.size() == 1 && cmd[0] == "keys") {
        return do_keys(cmd, out);
    }
    else {
        return out_err(out, ERR_UNKNOWN, "Unknown command");
    }
}

