int main() {
    //listening socket
    int fd = socket(AF_INET, SOCK_STREAM, 0);
    if(fd < 0) {
        die("socket()");
    }

    int val = 1;
    setsockopt(fd, SOL_SOCKET, SO_REUSEADDR, &val, sizeof(val));

    //bind
    struct sockaddr_in addr = {};
    addr.sin_family = AF_INET;              //Ipv4
    addr.sin_port = ntohs(1234);            //Port number
    addr.sin_addr.s_addr = ntohl(0);        //Wildcard Ip 0.0.0.0

    int rv = bind(fd, (const struct sockaddr *)&addr, sizeof(addr));
    if(rv) {
        die("bind()");
    }

    fd_set_nonblock(fd);                    //Set the listening socket to non-block

    //listen
    rv = listen(fd, SOMAXCONN);
    if(rv) {
        die("listen()"); 
    }

    //A map of all client connections that are keyed by fd
    std::vector<struct Conn *> fd2conn;
    //event loop
    std::vector<struct pollfd> poll_args;
    while(true) {
        //Prepare the arguments of the poll() syscall
        poll_args.clear();
        //Put the listening socket in the first position in the poll_args vector
        struct pollfd pfd = {fd, POLLIN, 0};
        poll_args.push_back(pfd);
        //All the rest are connection sockets
        
        for(struct Conn *conn : fd2conn) {
            if(!conn) {
                continue;
            }
            //always poll() for error
            struct pollfd pfd = {conn->fd, POLLERR, 0};
            //poll() flags from the applications intent
            if(conn->want_read) {
                pfd.events |= POLLIN;
            }
            if(conn->want_write) {
                pfd.events |= POLLOUT;
            }
            poll_args.push_back(pfd);
        }
        
        //wait for readiness
        int rv = poll(poll_args.data(), (nfds_t)poll_args.size(), -1);
        if(rv < 0 && errno == EINTR) {      //Sometimes unix signals may interrupt, which cause errno 
            continue;                       //Not an error
        }
        if(rv < 0) {
            die("poll()");
        }

        //handle the listening socket (The first one in fd list)
        if(poll_args[0].revents) {
            if(struct Conn *conn = handle_accept(fd)) {             //HANDLE_PROBLEM
                //put it into the map
                if(fd2conn.size() <= (size_t)conn->fd) {
                    fd2conn.resize(conn->fd + 1);
                }
                assert(!fd2conn[conn->fd]);
                fd2conn[conn->fd] = conn;
            }
        }

        //handle the connection sockets (all the rest)
        for(size_t i = 1; i < poll_args.size(); ++i) {          //Skipped 1st, cuz handled above
            uint32_t ready = poll_args[i].revents;
            if(ready == 0) {
                continue;
            }

            struct Conn *conn = fd2conn[poll_args[i].fd];
            if(ready & POLLIN) {
                assert(conn->want_read);
                handle_read(conn);           //application logic
            }
            if(ready & POLLOUT) {
                assert(conn->want_write);
                handle_write(conn);         //application logic
            }

            //Close the socket in case of socket error
            if((ready & POLLERR) || conn->want_close) {
                (void)close(conn->fd);
                fd2conn[conn->fd] = NULL;
                delete conn;
            }
        }       //The loop will run for each connection socket
    }       //The event loop

    return 0;
}

